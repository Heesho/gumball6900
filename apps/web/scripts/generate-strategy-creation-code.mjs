import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repositoryRoot = resolve(webRoot, '../..');
const outputPath = resolve(webRoot, 'lib/generated-strategy-creation-code.ts');
const check = process.argv.includes('--check');

const sources = [
  {
    artifact: 'packages/contracts/out/AcquisitionStrategy.sol/AcquisitionStrategy.json',
    exportName: 'acquisitionStrategyCreationCode',
  },
  {
    artifact: 'packages/contracts/out/ManagerRewards.sol/ManagerRewards.json',
    exportName: 'managerRewardsCreationCode',
  },
];

function chunks(value, size = 120) {
  const output = [];
  for (let offset = 0; offset < value.length; offset += size) output.push(value.slice(offset, offset + size));
  return output;
}

async function artifactBytecode(source) {
  const path = resolve(repositoryRoot, source.artifact);
  const artifact = JSON.parse(await readFile(path, 'utf8'));
  const object = artifact?.bytecode?.object;
  const linkReferences = artifact?.bytecode?.linkReferences;
  if (typeof object !== 'string' || !/^0x[\da-f]+$/iu.test(object) || object.length % 2 !== 0) {
    throw new Error(`${source.artifact} does not contain complete creation bytecode`);
  }
  if (typeof linkReferences !== 'object' || linkReferences === null || Object.keys(linkReferences).length !== 0) {
    throw new Error(`${source.artifact} contains unresolved library links`);
  }
  return object.slice(2).toLowerCase();
}

const declarations = [];
for (const source of sources) {
  const bytecode = await artifactBytecode(source);
  const rows = chunks(bytecode)
    .map((chunk) => `  '${chunk}',`)
    .join('\n');
  declarations.push(
    `const ${source.exportName}Chunks = [\n${rows}\n] as const;\n\n` +
      `export const ${source.exportName} = \`0x\${${source.exportName}Chunks.join('')}\` as Hex;`,
  );
}

const generated =
  '// Generated by scripts/generate-strategy-creation-code.mjs from exact Foundry artifacts. Do not edit.\n' +
  "import type { Hex } from 'viem';\n\n" +
  declarations.join('\n\n') +
  '\n';

if (check) {
  let current;
  try {
    current = await readFile(outputPath, 'utf8');
  } catch {
    throw new Error('Generated strategy creation code is missing; run pnpm strategy-code:generate');
  }
  if (current !== generated) {
    throw new Error('Generated strategy creation code is stale; run pnpm strategy-code:generate');
  }
} else {
  await writeFile(outputPath, generated);
}
